/**
 * Creates a new GP consultation record.
 *
 * If `aiGenerated` is true, the data is stored as-provided — no external
 * AI call is made here. Callers should use `generateSOAPNote` separately
 * when SOAP generation is needed.
 *
 * @param db   Database client
 * @param data Consultation input data
 * @returns    The created consultation (domain representation)
 */
export async function createConsultation(
  db: DbClient,
  data: CreateConsultationInput,
): Promise<Consultation> {
  // ── Validate required fields ─────────────────────────────────────────
  if (!data.patientId || typeof data.patientId !== 'string') {
    throw new Error('patientId is required');
  }

  if (!data.gpId || typeof data.gpId !== 'string') {
    throw new Error('gpId is required');
  }

  if (!data.date || typeof data.date !== 'string') {
    throw new Error('date is required');
  }

  if (!data.summary || typeof data.summary !== 'string' || !data.summary.trim()) {
    throw new Error('summary is required');
  }

  // ── Validate consultation type ───────────────────────────────────────
  const consultationType = data.consultationType?.trim().toUpperCase() || 'INITIAL';
  if (!VALID_CONSULTATION_TYPES.has(consultationType)) {
    throw new Error(
      `Invalid consultationType "${data.consultationType}". Valid values: ${[...VALID_CONSULTATION_TYPES].join(', ')}`,
    );
  }

  // ── Validate duration ────────────────────────────────────────────────
  if (data.duration !== undefined && data.duration !== null) {
    if (typeof data.duration !== 'number' || !Number.isInteger(data.duration) || data.duration < 1) {
      throw new Error('duration must be a positive integer (minutes)');
    }
  }

  // ── Build create payload ─────────────────────────────────────────────
  const createData: Record<string, unknown> = {
    patientId: data.patientId,
    gpId: data.gpId,
    date: parseDateString(data.date),
    consultationType,
    summary: data.summary.trim(),
    prescriptions: data.prescriptions ?? [],
    referrals: data.referrals ?? [],
    mbsItems: data.mbsItems ?? [],
    aiGenerated: data.aiGenerated ?? false,
  };

  if (data.duration !== undefined && data.duration !== null) {
    createData.duration = data.duration;
  }

  if (data.treatmentPlan?.trim()) {
    createData.treatmentPlan = data.treatmentPlan.trim();
  }

  if (data.followUp) {
    createData.followUp = new Date(data.followUp);
  }

  if (data.notes?.trim()) {
    createData.notes = data.notes.trim();
  }

  // ── SOAP fields (optional, provided when saving with AI-generated content)
  if (data.subjectiveNote?.trim()) {
    createData.subjectiveNote = data.subjectiveNote.trim();
  }
  if (data.objectiveNote?.trim()) {
    createData.objectiveNote = data.objectiveNote.trim();
  }
  if (data.assessmentNote?.trim()) {
    createData.assessmentNote = data.assessmentNote.trim();
  }
  if (data.planNote?.trim()) {
    createData.planNote = data.planNote.trim();
  }

  const record = await db.gPConsultation.create({
    data: createData as Parameters<typeof db.gPConsultation.create>[0]['data'],
  });

  return mapConsultation(record as Parameters<typeof mapConsultation>[0]);
}

/**
 * Generates a structured SOAP note using GPT-4o.
 *
 * Fetches patient context (profile, recent symptoms, metrics, and active
 * medications) and combines it with the GP's consultation notes to produce
 * a comprehensive clinical note for review.
 *
 * @param db               Database client
 * @param patientId        The `health_profiles.id` of the patient
 * @param consultationData The GP's notes and generation preferences
 * @returns                Structured SOAP note with disclaimer
 */
export async function generateSOAPNote(
  db: DbClient,
  patientId: string,
  consultationData: SOAPInput,
): Promise<SOAPNote> {
  if (!patientId || typeof patientId !== 'string') {
    throw new Error('patientId is required');
  }

  if (
    !consultationData.notes ||
    typeof consultationData.notes !== 'string' ||
    !consultationData.notes.trim()
  ) {
    throw new Error('notes are required for SOAP generation');
  }

  // ── Resolve API key ──────────────────────────────────────────────────
  const apiKey = await resolveOpenAiKey();
  if (!apiKey) {
    throw new Error(
      'OpenAI API key is not configured. The administrator needs to add an OpenAI API key.',
    );
  }

  // ── Build patient context ────────────────────────────────────────────
  const includeMetrics = consultationData.includeMetrics ?? true;
  const patientContext = await buildPatientContext(db, patientId, includeMetrics);

  // ── Build messages ───────────────────────────────────────────────────
  const userContent = [
    'Generate a comprehensive SOAP note based on the following information.',
    '',
    patientContext || 'No additional patient context available.',
    '',
    'GP NOTES:',
    consultationData.notes.trim(),
    '',
    'Return ONLY a valid JSON object with exactly four string fields: subjective, objective, assessment, plan.',
    'Each field should contain the respective section content in Markdown format.',
    'The assessment field MUST begin with "AI-ASSISTED — REQUIRES GP REVIEW".',
  ].join('\n');

  // ── Call OpenAI ──────────────────────────────────────────────────────
  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model: SOAP_MODEL,
      messages: [
        { role: 'system', content: SOAP_SYSTEM_PROMPT },
        { role: 'user', content: userContent },
      ],
      response_format: { type: 'json_object' },
      temperature: 0.5,
      max_tokens: 3000,
    }),
  });

  if (!response.ok) {
    let errorDetail = '';
    try {
      const errorBody = await response.json() as {
        error?: string | { message?: string };
      };
      if (typeof errorBody.error === 'string') {
        errorDetail = errorBody.error;
      } else if (
        errorBody.error &&
        typeof errorBody.error === 'object' &&
        typeof errorBody.error.message === 'string'
      ) {
        errorDetail = errorBody.error.message;
      }
    } catch {
      // ignore parse errors
    }

    const message = errorDetail || `OpenAI API returned status ${response.status}`;
    throw new Error(`SOAP generation failed: ${message}`);
  }

  const data = await response.json() as {
    choices?: {
      message?: {
        content?: string | null;
      };
    }[];
  };

  const content = data.choices?.[0]?.message?.content;
  if (!content || !content.trim()) {
    throw new Error('SOAP generation returned an empty response.');
  }

  // ── Parse and return ─────────────────────────────────────────────────
  const parsed = parseSOAPJsonResponse(content);

  return {
    subjective: parsed.subjective,
    objective: parsed.objective,
    assessment: parsed.assessment,
    plan: parsed.plan,
    disclaimer: SOAP_DISCLAIMER,
  };
}

/**
 * Returns consultation history for a patient, ordered by date descending
 * (newest first).
 *
 * @param db        Database client
 * @param patientId The patient's `health_profiles.id`
 * @returns         Array of consultations (domain representation)
 */
export async function getConsultations(
  db: DbClient,
  patientId: string,
): Promise<Consultation[]> {
  if (!patientId || typeof patientId !== 'string') {
    throw new Error('patientId is required');
  }

  const records = await db.gPConsultation.findMany({
    where: { patientId },
    orderBy: { date: 'desc' },
  });

  return records.map((r) =>
    mapConsultation(r as Parameters<typeof mapConsultation>[0]),
  );
}

/**
 * Returns a single consultation by its ID.
 *
 * @param db             Database client
 * @param consultationId The consultation's ID
 * @returns              The consultation, or `null` if not found
 */
export async function getConsultation(
  db: DbClient,
  consultationId: string,
): Promise<Consultation | null> {
  if (!consultationId || typeof consultationId !== 'string') {
    throw new Error('consultationId is required');
  }

  const record = await db.gPConsultation.findUnique({
    where: { id: consultationId },
  });

  if (!record) {
    return null;
  }

  return mapConsultation(record as Parameters<typeof mapConsultation>[0]);
}
