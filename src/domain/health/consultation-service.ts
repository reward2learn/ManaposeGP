// ── Constants ────────────────────────────────────────────────────────────────

const VALID_CONSULTATION_TYPES = new Set([
  'INITIAL',
  'FOLLOW_UP',
  'REVIEW',
  'EMERGENCY',
]);

const SOAP_MODEL = process.env.OPENAI_GP_CHAT_MODEL || 'gpt-4o';

const SOAP_DISCLAIMER =
  'AI-ASSISTED — REQUIRES GP REVIEW. This SOAP note was generated by an AI model and is intended as decision SUPPORT, not decision REPLACEMENT. The treating GP must review, verify, and approve all content before it becomes part of the medical record.';

const SOAP_SYSTEM_PROMPT = [
  "You are an AI scribe for Australian GPs. Generate a structured SOAP note from the provided patient data and GP notes.",
  '',
  'S (Subjective): Patient-reported symptoms, concerns, and history. Draw from symptom journal data.',
  'O (Objective): Vital signs, examination findings, lab results. Draw from health metrics.',
  'A (Assessment): Clinical assessment and differential diagnoses. Consider menopause status.',
  'P (Plan): Treatment plan, investigations, referrals, follow-up. Include MBS item numbers where relevant.',
  '',
  'Format: Markdown with clear section headers. Prefix the assessment with "AI-ASSISTED — REQUIRES GP REVIEW".',
  'Be specific. Reference relevant guidelines. Note: This is decision SUPPORT, not decision REPLACEMENT.',
].join('\n');

// ── Helpers ──────────────────────────────────────────────────────────────────

/** Parses a YYYY-MM-DD string to a Date. Throws on invalid input. */
function parseDateString(value: string): Date {
  if (!value || typeof value !== 'string') {
    throw new Error(`Invalid date: "${value}"`);
  }

  const trimmed = value.trim();
  const date = new Date(`${trimmed}T00:00:00.000Z`);
  if (Number.isNaN(date.getTime())) {
    throw new Error(`Invalid date: "${trimmed}"`);
  }

  return date;
}

/** Formats a Date as YYYY-MM-DD. */
function formatDate(date: Date): string {
  return date.toISOString().slice(0, 10);
}

/**
 * Maps a raw Prisma GPConsultation row (with `Date` fields) to the domain
 * `Consultation` interface (with ISO 8601 strings).
 */
function mapConsultation(row: {
  id: string;
  patientId: string;
  gpId: string;
  date: Date;
  consultationType: string;
  duration: number | null;
  summary: string;
  subjectiveNote: string | null;
  objectiveNote: string | null;
  assessmentNote: string | null;
  planNote: string | null;
  treatmentPlan: string | null;
  prescriptions: string[];
  referrals: string[];
  followUp: Date | null;
  mbsItems: string[];
  notes: string | null;
  aiGenerated: boolean;
}): Consultation {
  return {
    id: row.id,
    patientId: row.patientId,
    gpId: row.gpId,
    date: formatDate(row.date),
    consultationType: row.consultationType,
    duration: row.duration ?? undefined,
    summary: row.summary,
    subjectiveNote: row.subjectiveNote ?? undefined,
    objectiveNote: row.objectiveNote ?? undefined,
    assessmentNote: row.assessmentNote ?? undefined,
    planNote: row.planNote ?? undefined,
    treatmentPlan: row.treatmentPlan ?? undefined,
    prescriptions: row.prescriptions,
    referrals: row.referrals,
    followUp: row.followUp ? row.followUp.toISOString() : undefined,
    mbsItems: row.mbsItems,
    notes: row.notes ?? undefined,
    aiGenerated: row.aiGenerated,
  };
}

/**
 * Builds a clinical context string for the SOAP generation prompt
 * from patient profile, recent symptoms, health metrics, and medications.
 */
async function buildPatientContext(
  db: DbClient,
  patientId: string,
  includeMetrics: boolean,
): Promise<string> {
  const parts: string[] = [];

  // ── Patient profile ─────────────────────────────────────────────────
  const profile = await db.healthProfile.findUnique({
    where: { id: patientId },
    select: {
      dateOfBirth: true,
      sexAtBirth: true,
      menopauseStatus: true,
      heightCm: true,
      weightKg: true,
      bloodType: true,
      allergies: true,
      chronicConditions: true,
      currentMedications: true,
      smokingStatus: true,
      alcoholUnitsPerWeek: true,
      exerciseMinutesPerWeek: true,
      familyHistory: true,
    },
  });

  if (profile) {
    const profileLines: string[] = ['PATIENT PROFILE:'];
    if (profile.dateOfBirth) {
      const age = Math.floor(
        (Date.now() - profile.dateOfBirth.getTime()) /
          (365.25 * 24 * 60 * 60 * 1000),
      );
      profileLines.push(`- Age: ${age} (DOB: ${formatDate(profile.dateOfBirth)})`);
    }
    if (profile.sexAtBirth) {
      profileLines.push(`- Sex at birth: ${profile.sexAtBirth}`);
    }
    if (profile.menopauseStatus) {
      profileLines.push(`- Menopause status: ${profile.menopauseStatus}`);
    }
    if (profile.heightCm) {
      profileLines.push(`- Height: ${profile.heightCm} cm`);
    }
    if (profile.weightKg) {
      profileLines.push(`- Weight: ${profile.weightKg} kg`);
      if (profile.heightCm) {
        const bmi = profile.weightKg / ((profile.heightCm / 100) ** 2);
        profileLines.push(`- BMI: ${bmi.toFixed(1)}`);
      }
    }
    if (profile.bloodType) {
      profileLines.push(`- Blood type: ${profile.bloodType}`);
    }
    if (profile.allergies.length > 0) {
      profileLines.push(`- Allergies: ${profile.allergies.join(', ')}`);
    }
    if (profile.chronicConditions.length > 0) {
      profileLines.push(`- Chronic conditions: ${profile.chronicConditions.join(', ')}`);
    }
    if (profile.smokingStatus) {
      profileLines.push(`- Smoking status: ${profile.smokingStatus}`);
    }
    if (profile.alcoholUnitsPerWeek !== null) {
      profileLines.push(`- Alcohol: ${profile.alcoholUnitsPerWeek} units/week`);
    }
    if (profile.exerciseMinutesPerWeek !== null) {
      profileLines.push(`- Exercise: ${profile.exerciseMinutesPerWeek} min/week`);
    }
    if (profile.familyHistory) {
      profileLines.push(`- Family history: ${JSON.stringify(profile.familyHistory)}`);
    }
    parts.push(profileLines.join('\n'));
  }

  // ── Recent symptoms (last 30 days) ──────────────────────────────────
  const thirtyDaysAgo = new Date();
  thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);

  const symptoms = await db.symptomJournal.findMany({
    where: {
      healthProfileId: patientId,
      date: { gte: thirtyDaysAgo },
    },
    orderBy: { date: 'desc' },
  });

  if (symptoms.length > 0) {
    const symptomLines: string[] = ['RECENT SYMPTOMS (last 30 days):'];
    for (const s of symptoms) {
      const severityLabel = s.severity > 0 ? ` (severity: ${s.severity}/10)` : '';
      symptomLines.push(
        `- ${formatDate(s.date)}: ${s.symptomType}${severityLabel}${s.notes ? ` — ${s.notes}` : ''}`,
      );
    }
    parts.push(symptomLines.join('\n'));
  }

  // ── Health metrics (if requested) ───────────────────────────────────
  if (includeMetrics) {
    const metrics = await db.healthMetric.findMany({
      where: { healthProfileId: patientId },
      orderBy: { recordedAt: 'desc' },
      take: 30,
    });

    if (metrics.length > 0) {
      const metricLines: string[] = ['RECENT HEALTH METRICS:'];
      for (const m of metrics) {
        metricLines.push(
          `- ${m.recordedAt.toISOString()}: ${m.metricType} = ${typeof m.value === 'object' ? JSON.stringify(m.value) : String(m.value)}${m.unit ? ` ${m.unit}` : ''}`,
        );
      }
      parts.push(metricLines.join('\n'));
    }
  }

  // ── Active medications ──────────────────────────────────────────────
  const medications = await db.medication.findMany({
    where: {
      healthProfileId: patientId,
      status: { in: ['ACTIVE'] },
    },
    orderBy: { startDate: 'desc' },
  });

  if (medications.length > 0) {
    const medLines: string[] = ['ACTIVE MEDICATIONS:'];
    for (const med of medications) {
      medLines.push(
        `- ${med.name} (${med.type}): ${med.dosage}, ${med.frequency}${med.route ? `, ${med.route}` : ''} — started ${formatDate(med.startDate)}`,
      );
    }
    parts.push(medLines.join('\n'));
  }

  return parts.join('\n\n');
}

/**
 * Parses a SOAP note JSON response from the LLM into structured fields.
 * Falls back gracefully if the parsed JSON is malformed.
 */
function parseSOAPJsonResponse(
  responseText: string,
): Pick<SOAPNote, 'subjective' | 'objective' | 'assessment' | 'plan'> {
  // Try to extract a JSON object from the response (may contain markdown fences)
  let jsonStr = responseText.trim();

  // Remove markdown code fences if present
  const fenceMatch = jsonStr.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
  if (fenceMatch) {
    jsonStr = fenceMatch[1].trim();
  }

  try {
    const parsed = JSON.parse(jsonStr) as Record<string, unknown>;
    return {
      subjective:
        typeof parsed.subjective === 'string' && parsed.subjective.trim()
          ? parsed.subjective.trim()
          : 'No subjective data generated.',
      objective:
        typeof parsed.objective === 'string' && parsed.objective.trim()
          ? parsed.objective.trim()
          : 'No objective data generated.',
      assessment:
        typeof parsed.assessment === 'string' && parsed.assessment.trim()
          ? parsed.assessment.trim()
          : 'No assessment generated.',
      plan:
        typeof parsed.plan === 'string' && parsed.plan.trim()
          ? parsed.plan.trim()
          : 'No plan generated.',
    };
  } catch {
    // Fallback: return the raw text as assessment and note parsing failure
    return {
      subjective:
        'Unable to parse AI response. See raw output in assessment field.',
      objective:
        'Unable to parse AI response. See raw output in assessment field.',
      assessment: responseText.trim(),
      plan: 'Unable to parse AI response. See raw output in assessment field.',
    };
  }
}

